def fmt_float(val: Optional[float], decimals: int = 2) -> str:
    """Форматирование вещественного числа с русской запятой или прочерком."""
    if val is None:
        return "н/н"
    fmt = f"{{:.{decimals}f}}"
    res = fmt.format(val).replace(".", ",")
    return res


def calculate_row(
    ik_num: str,
    i1_str: str,
    cos_phi: float,
    tt_class: str,
    th_class: str,
    meter_class: str,
    delta_t: float,
    delta_L: float,
    apply_magnetic_field: bool = False
) -> Dict[str, Any]:
    """
    Расчет полного набора характеристик (29 граф) для одной точки (I1, cos_phi).
    """
    # 1. Параметры ТТ
    is_direct_tt = (tt_class == "Без ТТ")
    if is_direct_tt:
        delta_i: Optional[float] = 0.0
        theta_i: Optional[float] = 0.0
        tt_label = "-"
    else:
        tt_info = TT_PARAMS[tt_class]
        delta_i = tt_info["delta_i"].get(i1_str, 0.0)
        theta_i = tt_info["theta_i"].get(i1_str, 0.0)
        tt_label = tt_class

    # 2. Параметры ТН
    is_direct_th = (th_class == "Без ТН")
    if is_direct_th:
        delta_u: Optional[float] = 0.0
        theta_u: Optional[float] = 0.0
        th_label = "-"
        act_delta_L = 0.0
    else:
        th_info = TH_PARAMS[th_class]
        delta_u = th_info["delta_u"]
        theta_u = th_info["theta_u"]
        th_label = th_class
        act_delta_L = delta_L

    # 3. Тригонометрия
    sin_phi = math.sqrt(max(0.0, 1.0 - cos_phi**2))
    tan_phi = (sin_phi / cos_phi) if cos_phi > 0 else 0.0
    cot_phi = (cos_phi / sin_phi) if sin_phi > 0 else 0.0

    # 4. Угловая погрешность схемы (δθ)
    if is_direct_tt and is_direct_th:
        delta_theta_act = 0.0
        delta_theta_react = 0.0
    elif is_direct_th:
        # Без ТН, только ТТ
        theta_geom = theta_i or 0.0
        delta_theta_act = 0.029 * theta_geom * tan_phi
        delta_theta_react = 0.029 * theta_geom * cot_phi if sin_phi > 0 else 0.0
    else:
        # ТТ + ТН
        theta_geom = math.sqrt((theta_i or 0.0)**2 + (theta_u or 0.0)**2)
        delta_theta_act = 0.029 * theta_geom * tan_phi
        delta_theta_react = 0.029 * theta_geom * cot_phi if sin_phi > 0 else 0.0

    # 5. Параметры счетчика
    meter_prof = METER_BASE_PROFILES[meter_class]
    kt_c_act = meter_prof["class_act"]
    kt_c_react = meter_prof["class_react"]

    point_data = meter_prof["data"].get((i1_str, cos_phi))
    if point_data is None:
        # fallback to 5% point if 1(2)% is requested for class without 1%
        point_data = meter_prof["data"].get(("5", cos_phi))

    (dco_act, dco_react, Kt_act, Kt_react, dcU_act, dcU_react, dcf_act, dcf_react) = point_data

    # Температурная погрешность: δct = Kt * Δt
    dct_act = Kt_act * delta_t
    dct_react = (Kt_react * delta_t) if Kt_react is not None else None

    # Погрешность от внешнего магнитного поля
    if apply_magnetic_field and i1_str == "100" and math.isclose(cos_phi, 1.0, rel_tol=1e-3):
        if "0.2" in kt_c_act:
            dmi_act = 0.50
        elif "0.5" in kt_c_act:
            dmi_act = 1.00
        else:
            dmi_act = 2.00
        dmi_react = None
    else:
        dmi_act = 0.0
        dmi_react = None

    # 6. Основная погрешность ИК (δW_осн)
    # Для каналов прямого включения без ТТ и без ТН: δW_осн = 1.1 * δс.о
    if is_direct_tt and is_direct_th:
        dW_osn_act = 1.1 * dco_act
        sq_osn_act = dco_act**2
        if dco_react is not None:
            dW_osn_react = 1.1 * dco_react
            sq_osn_react = dco_react**2
        else:
            dW_osn_react = None
            sq_osn_react = None
    else:
        sq_osn_act = (delta_i or 0.0)**2 + (delta_u or 0.0)**2 + delta_theta_act**2 + act_delta_L**2 + dco_act**2
        dW_osn_act = 1.1 * math.sqrt(sq_osn_act)

        if dco_react is not None:
            sq_osn_react = (delta_i or 0.0)**2 + (delta_u or 0.0)**2 + delta_theta_react**2 + act_delta_L**2 + dco_react**2
            dW_osn_react = 1.1 * math.sqrt(sq_osn_react)
        else:
            dW_osn_react = None
            sq_osn_react = None

    # 7. Рабочая погрешность ИК (δW_раб)
    sq_add_act = (dct_act or 0.0)**2 + (dcU_act or 0.0)**2 + (dcf_act or 0.0)**2 + (dmi_act or 0.0)**2
    dW_rab_act = 1.1 * math.sqrt(sq_osn_act + sq_add_act)

    if sq_osn_react is not None and dct_react is not None and dcU_react is not None and dcf_react is not None:
        sq_add_react = dct_react**2 + dcU_react**2 + dcf_react**2 + (dmi_react or 0.0)**2
        dW_rab_react = 1.1 * math.sqrt(sq_osn_react + sq_add_react)
    else:
        dW_rab_react = None

    cos_str = "1,0" if math.isclose(cos_phi, 1.0, rel_tol=1e-3) else f"{cos_phi:.1f}".replace(".", ",")

    return {
        # Сводные колонки (15 шт):
        "ik": ik_num,
        "i1": i1_str,
        "cos_phi": cos_str,
        "cos_phi_float": cos_phi,
        "kt_tt": tt_label,
        "kt_th": th_label,
        "kt_meter": f"{kt_c_act} / {kt_c_react}",
        "delta_i": fmt_float(delta_i if not is_direct_tt else None, 2),
        "theta_i": fmt_float(theta_i if not is_direct_tt else None, 0),
        "delta_u": fmt_float(delta_u if not is_direct_th else None, 2),
        "theta_u": fmt_float(theta_u if not is_direct_th else None, 0),
        "delta_L": fmt_float(act_delta_L if not is_direct_th else None, 2),
        "dW_osn_act": fmt_float(dW_osn_act, 1),
        "dW_osn_react": fmt_float(dW_osn_react, 1),
        "dW_rab_act": fmt_float(dW_rab_act, 1),
        "dW_rab_react": fmt_float(dW_rab_react, 1),

        # Дополнительные колонки для полной таблицы (29 граф):
        "delta_theta_act": fmt_float(delta_theta_act if not (is_direct_tt and is_direct_th) else None, 2),
        "delta_theta_react": fmt_float(delta_theta_react if (cos_phi < 1.0 and not (is_direct_tt and is_direct_th)) else None, 2),
        "kt_meter_act": kt_c_act,
        "kt_meter_react": kt_c_react,
        "dco_act": fmt_float(dco_act, 2),
        "dco_react": fmt_float(dco_react, 2),
        "delta_t": fmt_float(delta_t, 0),
        "dct_act": fmt_float(dct_act, 2),
        "dct_react": fmt_float(dct_react, 2),
        "dcU_act": fmt_float(dcU_act, 2),
        "dcU_react": fmt_float(dcU_react, 2),
        "dcf_act": fmt_float(dcf_act, 2),
        "dcf_react": fmt_float(dcf_react, 2),
        "dmi_act": fmt_float(dmi_act if dmi_act > 0 else None, 1),
        "dmi_react": fmt_float(dmi_react, 1),
    }


def generate_group_table(
    ik_num: str,
    tt_class: str,
    th_class: str,
    meter_class: str,
    delta_t: float,
    delta_L: float = 0.25,
    apply_magnetic_field: bool = False
) -> List[Dict[str, Any]]:
    """
    Генерирует полную последовательность строк для измерительного канала / группы
    по всем нормируемым точкам тока и cos φ.
    """
    meter_prof = METER_BASE_PROFILES[meter_class]
    tt_info = TT_PARAMS[tt_class]

    # Определяем точки тока
    # Точка 1(2)% присутствует только если счетчик и ТТ поддерживают класс S
    include_1pct = meter_prof["has_1pct"] and ("S" in tt_class)
    if include_1pct:
        current_points = ["1(2)", "5", "20", "100", "120"]
    else:
        current_points = ["5", "20", "100", "120"]

    cos_points = [0.5, 0.8, 0.9, 1.0]

    rows = []
    for i1 in current_points:
        for cos_phi in cos_points:
            row = calculate_row(
                ik_num=ik_num,
                i1_str=i1,
                cos_phi=cos_phi,
                tt_class=tt_class,
                th_class=th_class,
                meter_class=meter_class,
                delta_t=delta_t,
                delta_L=delta_L,
                apply_magnetic_field=apply_magnetic_field
            )
            rows.append(row)
    return rows


